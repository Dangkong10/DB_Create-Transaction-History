-- 마이그레이션: customers.payer_names 추가 (은행 입금 문자 매칭용)
-- 날짜: 2026-08-03
-- 실행 위치: Supabase SQL Editor
-- 주의: 기존 데이터를 변경하지 않습니다 (컬럼 추가 + 기본값 '[]' 만).
--
-- 배경:
--   하나은행 입금 알림 문자에는 "입금자명" 이 찍힌다 (예: 지원숙).
--   이 이름을 거래처와 연결해 두어야 입금이 자동으로 잡힌다.
--
-- 왜 aliases 를 안 쓰고 새 컬럼을 만드는가:
--   aliases 는 **거래처 검색 전용**이다 (searchCustomers → matchChosung).
--   여기에 사람 이름을 넣으면 거래처 검색창에 "지원숙" 이 뜬다.
--   역할이 다르므로 컬럼을 분리한다.
--
--   단, 매칭할 때는 name 과 payer_names 를 **둘 다** 본다 —
--   상호로 입금하든 사람 이름으로 입금하든 같은 거래처로 잡혀야 하므로.
--   (aliases 는 매칭에 쓰지 않는다. "7조"·"켈리" 같은 내부 축약어가
--    은행 문자에 찍힐 일이 없고, 우연히 겹치면 오배정 위험만 생긴다.)
--
-- 매칭 규칙 (2026-08-03 확정):
--   · 입금자명이 name 과 완전 일치        → 자동 입금 처리
--   · 입금자명이 payer_names 중 하나와 완전 일치 → 자동 입금 처리
--   · 그 외 전부                          → 자동으로 절대 잡지 않음
--   부분 일치·초성 매칭·정규화 추정은 하지 않는다 (돈이 걸린 문제).
-- ============================================================

BEGIN;

ALTER TABLE public.customers
  ADD COLUMN IF NOT EXISTS payer_names JSONB NOT NULL DEFAULT '[]'::jsonb;

COMMENT ON COLUMN public.customers.payer_names IS
  '은행 입금 문자에 찍히는 입금자명 목록 (예: ["박태상"]). 검색용 aliases 와 별개 — 이 값은 거래처 검색에 노출되지 않는다. 완전 일치할 때만 자동 입금 매칭.';

COMMIT;

